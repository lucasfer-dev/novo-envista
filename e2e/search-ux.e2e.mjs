import { test, expect } from '@playwright/test';
test.use({ video: "off", channel: process.env.E2E_BROWSER_CHANNEL || undefined });
test('search keyboard, error recovery and mobile overflow',async({page})=>{
 await page.route('**/api/search?*',route=>route.fulfill({status:503,body:'{}'}));
 test.skip(!process.env.E2E_SEARCH_URL, 'Requires a page with GlobalSearchCommand and an authenticated session when applicable');
 await page.goto(process.env.E2E_SEARCH_URL);
 await page.getByRole('button',{name:/Atalho/}).click();
 const input=page.getByRole('combobox');
 await expect(input).toBeFocused();
 await expect(page.getByRole('button',{name:'Tentar novamente'})).toBeVisible();
 await input.press('Shift+Tab');
 await expect(page.getByRole('button',{name:'Tentar novamente'})).toBeFocused();
 await page.keyboard.press('Tab');await expect(input).toBeFocused();
 await page.unroute('**/api/search?*');
 await page.route('**/api/search?*',route=>route.fulfill({json:{items:Array.from({length:20},(_,i)=>({id:String(i),type:'project',title:'Project '+i,subtitle:'Test fixture',href:'/projects/'+i}))}}));
 await page.getByRole('button',{name:'Tentar novamente'}).click();
 await expect(page.getByRole('option')).toHaveCount(20);
 await page.mouse.move(0,0);
 await input.focus();
 await expect(page.getByRole('option').first()).toHaveAttribute('aria-selected','true');
 for(let i=0;i<19;i++)await input.press('ArrowDown');
 await expect(page.getByRole('option').last()).toBeInViewport();
 await input.press('Tab');await expect(page.getByRole('button',{name:'Fechar busca'})).toBeFocused();
 await page.keyboard.press('Tab');await expect(input).toBeFocused();
 await input.press('Escape');await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(page.getByRole('button',{name:/Atalho/})).toBeFocused();
 await page.setViewportSize({width:320,height:640});
 await page.getByRole('button',{name:/Atalho/}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
});
